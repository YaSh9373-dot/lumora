type StepTuple = [title: string, toolId: string | undefined, detail: string];

function wf(
  summary: string,
  steps: StepTuple[],
  generations: number,
  hoursSpent: number,
  postProduction: string[],
  promptExample?: string,
): Workflow {
  const mapped: WorkflowStep[] = steps.map(([title, toolId, detail]) => ({ title, toolId, detail }));
  return { summary, steps: mapped, generations, hoursSpent, postProduction, promptExample };
}

function piece(p: Omit<PortfolioPiece, "clientVerified" | "commercialUseCleared"> & Partial<PortfolioPiece>): PortfolioPiece {
  return { clientVerified: false, commercialUseCleared: true, ...p };
}

